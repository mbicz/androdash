package com.mbicz.androdash

/** One scrape target of the on-phone collector (C-001 `collector_targets`). */
data class CollectorTarget(
    val job: String,
    val instance: String,
    val address: String,
)

/**
 * Pure model of the on-phone Prometheus collector (decisions 0019, 0021):
 * validated targets, the in-app phone exporter job, scrape interval and
 * retention, the `prometheus.yml` text, and the command line. Everything
 * Prometheus sees is built from validated fields only.
 */
data class CollectorConfig(
    val targets: List<CollectorTarget>,
    val scrapeSeconds: Int,
    val retentionMillis: Long,
    /** C-001 `collector_phone`: run [PhoneExporter] and scrape it as [PHONE_TARGET]. */
    val phone: Boolean = false,
) {
    /** Every scrape target: [PHONE_TARGET] first when [phone], then [targets]. */
    val scrapeTargets: List<CollectorTarget>
        get() = if (phone) listOf(PHONE_TARGET) + targets else targets

    /**
     * Deterministic `prometheus.yml`: a global scrape interval and one scrape
     * job per distinct `job` (first-appearance order) whose static configs set
     * the `instance` label. No other Prometheus features are configured.
     */
    fun prometheusYaml(): String = buildString {
        append("# Generated by AndroDash from C-001 collector_targets. Do not edit.\n")
        append("global:\n")
        append("  scrape_interval: ").append(quote("${scrapeSeconds}s")).append('\n')
        append("scrape_configs:\n")
        scrapeTargets.groupBy { it.job }.forEach { (job, members) ->
            append("  - job_name: ").append(quote(job)).append('\n')
            append("    static_configs:\n")
            members.forEach { target ->
                append("      - targets: [").append(quote(target.address)).append("]\n")
                append("        labels:\n")
                append("          instance: ").append(quote(target.instance)).append('\n')
            }
        }
    }

    /**
     * Prometheus arguments. Loopback listener only; the admin API, lifecycle
     * API, and remote-write receiver stay at their disabled defaults.
     */
    fun arguments(binary: String, configFile: String, dataDir: String): List<String> = listOf(
        binary,
        "--config.file=$configFile",
        "--storage.tsdb.path=$dataDir",
        "--storage.tsdb.retention.time=${prometheusDuration(retentionMillis)}",
        "--web.listen-address=$LISTEN_ADDRESS",
        "--web.max-connections=$MAX_CONNECTIONS",
        "--log.level=warn",
    )

    companion object {
        const val LISTEN_ADDRESS = "127.0.0.1:19090"
        const val URL = "http://$LISTEN_ADDRESS"
        const val MAX_TARGETS = 32
        const val DEFAULT_JOB = "node"

        /** The in-app phone exporter's loopback listener ([PhoneExporter], C-008). */
        const val PHONE_PORT = 19100
        val PHONE_TARGET = CollectorTarget("phone", "phone", "127.0.0.1:$PHONE_PORT")
        private const val MAX_CONNECTIONS = 32
        private const val MAX_HOST = 253
        private val NAME = Regex("^[A-Za-z0-9_.-]{1,64}$")
        private val DNS_LABEL = Regex("^[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?$")
        private val IPV4_LIKE = Regex("^[0-9.]+$")
        private val PORT = Regex("^[1-9][0-9]{0,4}$")
        private val HEX_GROUP = Regex("^[0-9A-Fa-f]{1,4}$")

        /**
         * The collector for [config], or null when `collector=false`. It needs
         * `collector_targets`, `collector_phone=true`, or both; a user target
         * may not repeat the phone job's `phone`/`phone` job and instance.
         */
        fun from(config: AppConfig): CollectorConfig? {
            if (!config.collector) return null
            val targets = config.collectorTargets?.let(::parseTargets).orEmpty()
            if (targets.isEmpty() && !config.collectorPhone) {
                throw ConfigException(
                    "E_CONFIG",
                    "collector=true needs collector_targets or collector_phone=true",
                )
            }
            if (config.collectorPhone &&
                targets.any { it.job == PHONE_TARGET.job && it.instance == PHONE_TARGET.instance }
            ) {
                throw ConfigException("E_CONFIG", "collector_targets repeats the phone job and instance")
            }
            return CollectorConfig(
                targets = targets,
                scrapeSeconds = config.collectorScrapeSeconds,
                retentionMillis = ConfigParser.collectorRetentionMillis(config.collectorRetention),
                phone = config.collectorPhone,
            )
        }

        /**
         * Parse `collector_targets`: comma-separated `[job:]instance=host:port`
         * or `host:port`. `job` defaults to `node`, `instance` to `host:port`.
         * Blank entries are skipped. Invalid input is `E_CONFIG`.
         */
        fun parseTargets(raw: String): List<CollectorTarget> {
            val entries = raw.split(",").map { it.trim() }.filter { it.isNotEmpty() }
            if (entries.isEmpty()) {
                throw ConfigException("E_CONFIG", "collector_targets must contain at least one target")
            }
            if (entries.size > MAX_TARGETS) {
                throw ConfigException("E_CONFIG", "collector_targets must contain at most $MAX_TARGETS targets")
            }
            val targets = entries.map(::parseTarget)
            if (targets.map { it.job to it.instance }.distinct().size != targets.size) {
                throw ConfigException("E_CONFIG", "collector_targets repeats a job and instance")
            }
            return targets
        }

        /** Canonical stored form: the trimmed, non-blank entries joined by `,`. */
        fun canonicalTargets(targets: List<CollectorTarget>): String =
            targets.joinToString(",") { target ->
                if (target.job == DEFAULT_JOB && target.instance == target.address) {
                    target.address
                } else {
                    "${target.job}:${target.instance}=${target.address}"
                }
            }

        /** Prometheus duration text (descending `d`, `h`, `m`, `s`, `ms` parts). */
        fun prometheusDuration(millis: Long): String {
            require(millis > 0) { "duration must be positive" }
            var rest = millis
            return buildString {
                for ((unit, size) in DURATION_UNITS) {
                    val count = rest / size
                    if (count > 0) {
                        append(count).append(unit)
                        rest -= count * size
                    }
                }
            }
        }

        private val DURATION_UNITS = listOf(
            "d" to 86_400_000L,
            "h" to 3_600_000L,
            "m" to 60_000L,
            "s" to 1_000L,
            "ms" to 1L,
        )

        private fun parseTarget(entry: String): CollectorTarget {
            val equals = entry.indexOf('=')
            if (equals < 0) {
                return CollectorTarget(DEFAULT_JOB, validateAddress(entry), entry)
            }
            val labels = entry.substring(0, equals)
            val address = validateAddress(entry.substring(equals + 1))
            val colon = labels.indexOf(':')
            val job = if (colon < 0) DEFAULT_JOB else labels.substring(0, colon)
            val instance = if (colon < 0) labels else labels.substring(colon + 1)
            if (!NAME.matches(job)) {
                throw ConfigException("E_CONFIG", "collector_targets job must match [A-Za-z0-9_.-]{1,64}")
            }
            if (!NAME.matches(instance)) {
                throw ConfigException("E_CONFIG", "collector_targets instance must match [A-Za-z0-9_.-]{1,64}")
            }
            return CollectorTarget(job, instance, address)
        }

        /** `host:port` with a DNS name, IPv4 address, or bracketed IPv6 address. */
        private fun validateAddress(address: String): String {
            val host: String
            val port: String
            if (address.startsWith("[")) {
                val close = address.indexOf("]:")
                if (close < 0 || !isIpv6(address.substring(1, close))) {
                    throw ConfigException("E_CONFIG", "collector_targets has an invalid IPv6 address")
                }
                host = address.substring(0, close + 1)
                port = address.substring(close + 2)
            } else {
                val colon = address.lastIndexOf(':')
                if (colon <= 0) {
                    throw ConfigException("E_CONFIG", "collector_targets entries need host:port")
                }
                host = address.substring(0, colon)
                port = address.substring(colon + 1)
                if (!isHostName(host)) {
                    throw ConfigException("E_CONFIG", "collector_targets has an invalid host")
                }
            }
            val portNumber = if (PORT.matches(port)) port.toInt() else 0
            if (portNumber !in 1..65535) {
                throw ConfigException("E_CONFIG", "collector_targets port must be 1-65535")
            }
            return "$host:$port"
        }

        private fun isHostName(host: String): Boolean {
            if (host.isEmpty() || host.length > MAX_HOST) return false
            if (IPV4_LIKE.matches(host)) return isIpv4(host)
            return host.split('.').all { DNS_LABEL.matches(it) }
        }

        private fun isIpv4(text: String): Boolean {
            val parts = text.split('.')
            return parts.size == 4 && parts.all { part ->
                part.length in 1..3 &&
                    part.all { it in '0'..'9' } &&
                    (part.length == 1 || part[0] != '0') &&
                    part.toInt() <= 255
            }
        }

        private fun isIpv6(text: String): Boolean {
            if (text.isEmpty() || text.length > 45) return false
            var body = text
            val lastColon = body.lastIndexOf(':')
            if (lastColon < 0) return false
            val tail = body.substring(lastColon + 1)
            if (tail.contains('.')) {
                if (!isIpv4(tail)) return false
                body = body.substring(0, lastColon + 1) + "0:0"
            }
            val gap = body.indexOf("::")
            if (gap < 0) {
                val groups = body.split(':')
                return groups.size == 8 && groups.all { HEX_GROUP.matches(it) }
            }
            if (body.indexOf("::", gap + 1) >= 0) return false
            val left = body.substring(0, gap).let { if (it.isEmpty()) emptyList() else it.split(':') }
            val right = body.substring(gap + 2).let { if (it.isEmpty()) emptyList() else it.split(':') }
            return (left + right).all { HEX_GROUP.matches(it) } && left.size + right.size <= 7
        }

        /** Validated values never contain `"` or `\`; quoting keeps YAML from typing them. */
        private fun quote(value: String): String {
            require(value.none { it == '"' || it == '\\' || it < ' ' }) { "unquotable value" }
            return "\"$value\""
        }
    }
}
