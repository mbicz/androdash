package com.mbicz.androdash

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Assert.fail
import org.junit.Test

class CollectorConfigTest {
    @Test
    fun `entries parse with job and instance defaults`() {
        val targets = CollectorConfig.parseTargets(
            " node:mac=192.168.192.16:9100 , spark=spark.lan:9200,10.0.0.5:9100,gpu:dgx=[fd00::1]:9400 ",
        )
        assertEquals(
            listOf(
                CollectorTarget("node", "mac", "192.168.192.16:9100"),
                CollectorTarget("node", "spark", "spark.lan:9200"),
                CollectorTarget("node", "10.0.0.5:9100", "10.0.0.5:9100"),
                CollectorTarget("gpu", "dgx", "[fd00::1]:9400"),
            ),
            targets,
        )
        assertEquals(
            "node:mac=192.168.192.16:9100,node:spark=spark.lan:9200,10.0.0.5:9100,gpu:dgx=[fd00::1]:9400",
            CollectorConfig.canonicalTargets(targets),
        )
        assertEquals(targets, CollectorConfig.parseTargets(CollectorConfig.canonicalTargets(targets)))
    }

    @Test
    fun `blank entries are skipped but an empty list is rejected`() {
        assertEquals(1, CollectorConfig.parseTargets("a.lan:1,, ,").size)
        listOf("", " ", ",", " , ").forEach { assertInvalid(it) }
    }

    @Test
    fun `at most 32 targets`() {
        val ok = (1..32).joinToString(",") { "host$it:9100" }
        assertEquals(32, CollectorConfig.parseTargets(ok).size)
        assertInvalid("$ok,host33:9100")
    }

    @Test
    fun `invalid entries are E_CONFIG`() {
        listOf(
            "host",
            "host:",
            ":9100",
            "host:0",
            "host:65536",
            "host:09100",
            "host:+80",
            "host:port",
            "-bad.lan:9100",
            "bad-.lan:9100",
            "under_score.lan:9100",
            "a..b:9100",
            "a b:9100",
            "256.1.1.1:9100",
            "1.2.3:9100",
            "01.2.3.4:9100",
            "fd00::1:9100",
            "[fd00::1]",
            "[fd00::1]9100",
            "[fd00:::1]:9100",
            "[1:2:3:4:5:6:7:8:9]:9100",
            "[fd00::1%eth0]:9100",
            "[gggg::1]:9100",
            "=host:9100",
            "node:=host:9100",
            ":mac=host:9100",
            "job:in:st=host:9100",
            "mac=host",
            "${"j".repeat(65)}:mac=host:9100",
            "node:${"i".repeat(65)}=host:9100",
            "mac\"=host:9100",
            "mac=host:9100\nscrape_configs:",
            "${"a".repeat(64)}.lan:9100",
            "user@host:9100",
            "http://host:9100",
        ).forEach { assertInvalid(it) }
    }

    @Test
    fun `valid host forms`() {
        listOf(
            "localhost:9100",
            "a.b-c.example:1",
            "${"a".repeat(63)}.lan:65535",
            "[::1]:9100",
            "[::]:9100",
            "[1:2:3:4:5:6:7:8]:9100",
            "[::ffff:192.168.0.1]:9100",
            "[FD00:AB::1]:9100",
            "0.0.0.0:9100",
        ).forEach { assertEquals(it, CollectorConfig.parseTargets(it).single().address) }
    }

    @Test
    fun `duplicate job and instance is rejected, same address under two instances is allowed`() {
        assertInvalid("mac=a.lan:9100,mac=b.lan:9100")
        assertInvalid("a.lan:9100,a.lan:9100")
        assertEquals(2, CollectorConfig.parseTargets("node:mac=a.lan:9100,other:mac=a.lan:9100").size)
        assertEquals(2, CollectorConfig.parseTargets("one=a.lan:9100,two=a.lan:9100").size)
    }

    @Test
    fun `yaml groups targets by job in first-appearance order with quoted values`() {
        val config = CollectorConfig(
            targets = CollectorConfig.parseTargets("node:mac=192.168.192.16:9100,gpu:dgx=[fd00::1]:9400,10.0.0.5:9100"),
            scrapeSeconds = 15,
            retentionMillis = 86_400_000L,
        )
        val expected = """
            |# Generated by AndroDash from C-001 collector_targets. Do not edit.
            |global:
            |  scrape_interval: "15s"
            |scrape_configs:
            |  - job_name: "node"
            |    static_configs:
            |      - targets: ["192.168.192.16:9100"]
            |        labels:
            |          instance: "mac"
            |      - targets: ["10.0.0.5:9100"]
            |        labels:
            |          instance: "10.0.0.5:9100"
            |  - job_name: "gpu"
            |    static_configs:
            |      - targets: ["[fd00::1]:9400"]
            |        labels:
            |          instance: "dgx"
            |
        """.trimMargin()
        assertEquals(expected, config.prometheusYaml())
        assertEquals(expected, config.copy().prometheusYaml())
        listOf("remote_write", "rule_files", "file_sd", "alerting").forEach {
            assertFalse(config.prometheusYaml().contains(it))
        }
    }

    @Test
    fun `arguments are loopback only and enable no extra APIs`() {
        val config = CollectorConfig(
            targets = CollectorConfig.parseTargets("a.lan:9100"),
            scrapeSeconds = 30,
            retentionMillis = 5_400_000L,
        )
        assertEquals(
            listOf(
                "/lib/libprometheus.so",
                "--config.file=/files/collector/prometheus.yml",
                "--storage.tsdb.path=/files/collector/data",
                "--storage.tsdb.retention.time=1h30m",
                "--web.listen-address=127.0.0.1:19090",
                "--web.max-connections=32",
                "--log.level=warn",
            ),
            config.arguments("/lib/libprometheus.so", "/files/collector/prometheus.yml", "/files/collector/data"),
        )
        val joined = config.arguments("b", "c", "d").joinToString(" ")
        listOf("admin-api", "lifecycle", "remote-write-receiver", "0.0.0.0").forEach {
            assertFalse(joined.contains(it))
        }
    }

    @Test
    fun `prometheus durations are canonical descending units`() {
        assertEquals("1d", CollectorConfig.prometheusDuration(86_400_000L))
        assertEquals("30d", CollectorConfig.prometheusDuration(30L * 86_400_000L))
        assertEquals("1h30m", CollectorConfig.prometheusDuration(5_400_000L))
        assertEquals("1d2h3m4s5ms", CollectorConfig.prometheusDuration(93_784_005L))
        assertEquals("14d", CollectorConfig.prometheusDuration(2L * 604_800_000L))
    }

    @Test
    fun `from config reads collector fields`() {
        val base = AppConfig(dashboardUrl = "http://androdash.local/dashboards/macos-node-dashboard.json")
        assertNull(CollectorConfig.from(base))
        assertNull(CollectorConfig.from(base.copy(collectorTargets = "a.lan:9100")))
        val collector = CollectorConfig.from(
            base.copy(
                collector = true,
                collectorTargets = "mac=a.lan:9100",
                collectorScrapeSeconds = 10,
                collectorRetention = "2d",
                collectorPhone = false,
            ),
        )!!
        assertEquals(listOf(CollectorTarget("node", "mac", "a.lan:9100")), collector.targets)
        assertEquals(collector.targets, collector.scrapeTargets)
        assertFalse(collector.phone)
        assertEquals(10, collector.scrapeSeconds)
        assertEquals(2L * 86_400_000L, collector.retentionMillis)
        assertTrue(collector.prometheusYaml().contains("scrape_interval: \"10s\""))
        assertFalse(collector.prometheusYaml().contains("phone"))
    }

    @Test
    fun `collector_phone adds the phone job first and allows no other targets`() {
        val base = AppConfig(dashboardUrl = "http://androdash.local/dashboards/phone-dashboard.json", collector = true)
        val phoneOnly = CollectorConfig.from(base)!!
        assertTrue(phoneOnly.phone)
        assertTrue(phoneOnly.targets.isEmpty())
        assertEquals(listOf(CollectorTarget("phone", "phone", "127.0.0.1:19100")), phoneOnly.scrapeTargets)
        assertEquals(
            """
            |# Generated by AndroDash from C-001 collector_targets. Do not edit.
            |global:
            |  scrape_interval: "15s"
            |scrape_configs:
            |  - job_name: "phone"
            |    static_configs:
            |      - targets: ["127.0.0.1:19100"]
            |        labels:
            |          instance: "phone"
            |
            """.trimMargin(),
            phoneOnly.prometheusYaml(),
        )
        val both = CollectorConfig.from(base.copy(collectorTargets = "mac=a.lan:9100"))!!
        assertEquals(
            listOf(CollectorConfig.PHONE_TARGET, CollectorTarget("node", "mac", "a.lan:9100")),
            both.scrapeTargets,
        )
        // Only the phone job's own job+instance collides; other phone-job instances are fine.
        assertEquals(2, CollectorConfig.from(base.copy(collectorTargets = "phone:tablet=b.lan:9100"))!!.scrapeTargets.size)
        assertEquals(
            1,
            CollectorConfig.from(base.copy(collectorTargets = "phone:phone=b.lan:9100", collectorPhone = false))!!
                .scrapeTargets.size,
        )
        listOf(
            base.copy(collectorPhone = false),
            base.copy(collectorTargets = "phone:phone=b.lan:9100"),
        ).forEach { config ->
            try {
                CollectorConfig.from(config)
                fail("Expected E_CONFIG for $config")
            } catch (error: ConfigException) {
                assertEquals("E_CONFIG", error.code)
            }
        }
    }

    private fun assertInvalid(raw: String) {
        try {
            CollectorConfig.parseTargets(raw)
            fail("Expected E_CONFIG for '$raw'")
        } catch (error: ConfigException) {
            assertEquals("E_CONFIG", error.code)
        }
    }
}
